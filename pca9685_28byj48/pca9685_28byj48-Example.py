from machine import Pin, I2C
from pca9685_28byj48 import PCA9685Board


# ============================================================
# I2C
# ============================================================

i2c = I2C(
    0,
    scl=Pin(35),
    sda=Pin(33),
    freq=400_000
)


print("I2C:", [
    hex(x) for x in i2c.scan()
])


# ============================================================
# PCA9685 #1
# ============================================================

board1 = PCA9685Board(
    i2c,
    address=0x40,
    oe_pin=5
)

board1.set_speed(10)


# ============================================================
# PCA9685 #2
# ============================================================

board2 = PCA9685Board(
    i2c,
    address=0x41,
    oe_pin=6
)

board2.set_speed(5)


# ============================================================
# Motores
# ============================================================

motor1 = board1.motor(0)
motor2 = board1.motor(1)

motor3 = board2.motor(0)
motor4 = board2.motor(1)


# ============================================================
# Ejemplo
# ============================================================

motor1.cw()       # 10 RPM
motor2.ccw()      # 10 RPM

motor3.cw()       # 5 RPM
motor4.ccw()      # 5 RPM